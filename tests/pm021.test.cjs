const assert=require('node:assert/strict');
const {parsePositions,parseBalances,model,csvRows}=require('../pm021.js');
assert.equal(csvRows('"a,b","c""d"\n')[0][0],'a,b');
const csv='"Symbol","Qty (Quantity)","Price","Asset Type"\n"SOXL","100","50","Equity"\n"SOXL 11/20/2026 52.00 P","-1","4.8","Option"\n';
const p=parsePositions(csv);
assert.equal(p.puts.length,1);assert.equal(p.missing.length,0);
const r=model(p,{marginEquity:100000,maintenance:20000,drop:.2,houseFactor:1.5,timeFactor:2});
assert.equal(r.nominal,5200);assert.ok(Math.abs(r.stockLoss-3000)<1e-8);assert.ok(r.putLoss>0);
assert.ok(r.stressReq>20000);
assert.equal(model(p,{marginEquity:100000,maintenance:20000,drop:0,houseFactor:1,timeFactor:1}).baseExcess,80000);
const missing=parsePositions('"Symbol","Qty (Quantity)","Price","Asset Type"\n"JNUG 11/20/2026 140.00 P","-1","9.95","Option"\n');
assert.deepEqual(missing.missing,['JNUG']);
assert.throws(()=>model(missing,{marginEquity:100000,maintenance:20000,drop:.2}),/Fehlende Basiswerte/);
const etf=parsePositions('"Symbol","Qty (Quantity)","Price","Asset Type"\n"ETHT","700","11.3378","ETFs & Closed End Funds"\n');
assert.equal(etf.stocks.length,1);
assert.equal(etf.stocks[0].leverage,2);
const etfStress=model(etf,{marginEquity:100000,maintenance:20000,drop:.2,houseFactor:1.5,timeFactor:2});
assert.ok(Math.abs(etfStress.stockLoss-700*11.3378*.4)<1e-7);
const callCsv='"Symbol","Qty (Quantity)","Price","Asset Type"\n"ABC","100","50","Equity"\n"ABC 11/20/2026 45.00 C","-1","7","Option"\n';
const callPortfolio=parsePositions(callCsv);
const callStress=model(callPortfolio,{marginEquity:100000,maintenance:20000,drop:.2,houseFactor:1.5,timeFactor:2});
assert.ok(callStress.callLoss<0,'covered call should gain value on underlying decline with this fixture');
assert.ok(Math.abs(callStress.totalLoss-(callStress.stockLoss+callStress.putLoss+callStress.callLoss))<1e-8);
const missingCall=parsePositions('"Symbol","Qty (Quantity)","Price","Asset Type"\n"XYZ 11/20/2026 45.00 C","-1","2","Option"\n');
assert.deepEqual(missingCall.missing,['XYZ']);
const balances=parseBalances('"Balances for account XXXX as of 11/10/2026 06:18 AM ET"\nAccount Value,"$516,978.23"\nMargin Equity,"$349,464.65"\nEquity Percent,"67%"\nCash Secured Put Requirement,"$144,900.00"\n');
assert.equal(balances.accountValue,516978.23);
assert.equal(balances.marginEquity,349464.65);
assert.equal(balances.cashSecuredPutRequirement,144900);
assert.ok(Number.isNaN(balances.maintenance),'maintenance must not be invented');
assert.throws(()=>parseBalances('Foo,12\\n'),/Account Value oder Margin Equity fehlt/);
console.log('PM-021 CSV and scenario tests passed');
